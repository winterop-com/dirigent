"""Generate docs/architecture-model.md from the Structurizr Mermaid export.

Reads ``architecture/exports/mermaid/structurizr-<ViewKey>.mmd``, written by ``structurizr
export -format mermaid``, and rewrites each view into native Mermaid that MkDocs Material
renders: the HTML ``<div>`` labels are collapsed to plain text with ``<br/>`` breaks, and every
``style`` and ``linkStyle`` line is dropped so a diagram follows the site's light and dark
palettes. Node shapes survive; colours and technology logos do not.

Regenerate with ``make architecture-export-docs``; the output is never edited by hand.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPORT_DIR = ROOT / "architecture" / "exports" / "mermaid"
OUT = ROOT / "docs" / "architecture-model.md"

VIEWS: list[tuple[str, str]] = [
    ("L1_Landscape", "L1 - System landscape"),
    ("L2_Dirigent", "L2 - Containers: Dirigent"),
    ("L3_Server", "L3 - Components: API server"),
    ("L3_Worker", "L3 - Components: engine and worker"),
    ("Flow_AdHocRun", "Flow - An ad hoc run"),
    ("Flow_EndpointReply", "Flow - An endpoint source with a reply"),
    ("Flow_PolledSource", "Flow - A polled source"),
    ("Deploy_Compose", "Deployment - Docker Compose"),
    ("Deploy_Dev", "Deployment - dg dev"),
]


def clean_label(inner: str) -> str:
    """Collapse the HTML ``<div>`` label Structurizr emits into plain text and ``<br/>``."""
    parts = re.findall(r"<div[^>]*>(.*?)</div>", inner, re.DOTALL)
    cleaned = [re.sub(r"\s+", " ", p.replace("<br />", " ")).strip() for p in parts]
    return "<br/>".join(p for p in cleaned if p)


def clean_diagram(text: str) -> str:
    """Rewrite one exported ``.mmd`` into Mermaid MkDocs renders in either palette."""
    text = re.sub(
        r'"((?:[^"]*<div[^"]*))"',
        lambda m: '"' + clean_label(m.group(1)) + '"',
        text,
    )
    lines = [line for line in text.splitlines() if not line.strip().startswith(("style ", "linkStyle "))]
    return "\n".join(lines).strip()


def main() -> None:
    """Write the page from every exported view, the known ones first and in reading order."""
    if not EXPORT_DIR.exists():
        raise SystemExit(f"missing {EXPORT_DIR}; run `make architecture-export-docs`")

    found = {p.stem.removeprefix("structurizr-"): p for p in EXPORT_DIR.glob("structurizr-*.mmd")}
    known = {key for key, _ in VIEWS}
    ordered = list(VIEWS) + [(k, k) for k in sorted(found) if k not in known]

    out: list[str] = [
        "# Architecture model",
        "",
        "<!-- GENERATED by `make architecture-export-docs` from architecture/workspace.dsl. Do not edit by hand. -->",
        "",
        "A C4 model of Dirigent, generated from the Structurizr model in",
        "`architecture/workspace.dsl`. Every box is labelled with its type. For the interactive",
        "viewer, with zoom and click-through between levels, see `architecture/README.md`.",
        "",
        "What each package is for, and what may depend on what, is on",
        "[the architecture page](architecture.md).",
        "",
    ]
    for key, title in ordered:
        path = found.get(key)
        if path is None:
            continue
        diagram = clean_diagram(path.read_text())
        out += [f"## {title}", "", "```mermaid", diagram, "```", ""]

    OUT.write_text("\n".join(out).rstrip("\n") + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({sum(1 for k, _ in ordered if k in found)} views)")


if __name__ == "__main__":
    main()
